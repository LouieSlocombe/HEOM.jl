# Independent physical references, rather than a second implementation of the HEOM RHS.
# QBM: Fleming, Roura and Hu, Ann. Phys. 326, 1207 (2011), arXiv:1004.1603.
# Sextic eigenstate: Lévai and Ishkhanyan, arXiv:1904.09488, Eqs. (2)-(3).

@testset "Free and uniformly accelerated Gaussian wavepacket" begin
    m, ħ = 1.4, 0.8
    μ0, Σ0 = [-0.7, 0.5], [0.6 0.12; 0.12 0.5]
    grid = PhaseSpaceGrid((-9, 9), 72, (-7, 7), 64)
    W0 = on_grid((q, p) -> gaussian_wigner(q, p; mean = μ0, covariance = Σ0), grid)
    times = [0.0, 0.4, 1.1]
    for force in (0.0, 0.65)
        prob = wigner_moyal_problem(
            W0,
            (0.0, last(times)),
            grid;
            mass = m,
            hbar = ħ,
            potential = q -> -force * q,
        )
        sol = solve(prob, Vern7(); abstol = 1e-11, reltol = 1e-11, saveat = times)
        for (t, W) in zip(sol.t, sol.u)
            # Hamilton's exact affine flow transports the entire Gaussian, including
            # its position-momentum correlation and ballistic position spreading.
            F = [1 t/m; 0 1]
            μ = F * μ0 + [force * t^2 / (2m), force * t]
            Σ = F * Σ0 * F'
            exact = on_grid((q, p) -> gaussian_wigner(q, p; mean = μ, covariance = Σ), grid)
            @test max_error(W, exact) < 2e-9
            @test phase_space_mean(W, grid) ≈ μ atol = 2e-9
            @test phase_space_covariance(W, grid) ≈ Σ atol = 2e-9
            @test purity(W, grid; hbar = ħ) ≈ ħ / (2sqrt(det(Σ0))) atol = 2e-10
        end
    end
end

@testset "Exact sextic ground state needs the ħ⁴ Moyal term" begin
    m, ħ, a, b = 1.3, 0.8, 0.04, 0.45
    # ψ(q) = N exp(-a q⁴-b q²) solves the Schrödinger equation with E=ħ²b/m.
    # Derive V from ψ''/ψ, without invoking any Wigner or Moyal derivatives.
    V(q) = ħ^2 / (2m) * (16a^2 * q^6 + 16a * b * q^4 + (4b^2 - 12a) * q^2)
    grid = PhaseSpaceGrid((-7, 7), 96, (-9, 9), 128)
    dx, dy = 1 / 64, 1 / 16
    xs, ys = -8:dx:8, -16:dy:16
    norm_squared = inv(dx * sum(exp(-2a * x^4 - 2b * x^2) for x in xs))
    # Direct quadrature of the defining density-matrix transform. It neither uses
    # the solver's FFT nor its finite-difference/automatic-differentiation helpers.
    W = on_grid(grid) do q, p
        norm_squared * dy / (2π * ħ) * sum(
            exp(
                -a * ((q + y / 2)^4 + (q - y / 2)^4) - b * ((q + y / 2)^2 + (q - y / 2)^2),
            ) * cos(p * y / ħ) for y in ys
        )
    end
    @test phase_space_integral(W, grid) ≈ 1 atol = 2e-12
    @test purity(W, grid; hbar = ħ) ≈ 1 atol = 2e-12
    @test energy(W, grid; mass = m, potential = V) ≈ ħ^2 * b / m atol = 2e-11
    for moyal_terms in (nothing, 3)
        op = wigner_moyal_operator(grid; mass = m, hbar = ħ, potential = V, moyal_terms)
        @test maximum(abs, rhs(op, W)) < 2e-9
    end
    # The same non-Gaussian eigenstate is not stationary when either quantum
    # correction is omitted; a harmonic benchmark cannot detect these errors.
    for moyal_terms in (1, 2)
        op = wigner_moyal_operator(grid; mass = m, hbar = ħ, potential = V, moyal_terms)
        @test maximum(abs, rhs(op, W)) > 1e-3
    end
end

# Exact Gaussian dynamics of the linear generalized Langevin equation. Each retained
# positive real exponential of C(t) is generated by an auxiliary Ornstein-Uhlenbeck
# force. Its initial stationary variance is real(cₖ), independent of the system;
# feedback -2imag(cₖ)q/ħ produces the retarded dissipation. The physical force includes
# the counterterm from t=0, so this reference retains the factorized initial slip.
# This is exact for the specified exponential/delta bath, not for omitted Matsubara
# frequencies. It must therefore be converged separately from the bath expansion.
function gaussian_memory_reference(t, μ0, Σ0, bath; mass, omega)
    modes = length(bath.rates)
    dim = modes + 2
    A, Q, Σinitial = zeros(dim, dim), zeros(dim, dim), zeros(dim, dim)
    A[1, 2] = 1 / mass
    A[2, 1] = -mass * omega^2 - 2bath.counterterm
    Q[2, 2] = 2bath.diffusion
    Σinitial[1:2, 1:2] = Σ0
    for k in 1:modes
        @assert real(bath.coefficients[k]) > 0
        A[2, k+2] = 1
        A[k+2, 1] = -2imag(bath.coefficients[k]) / bath.hbar
        A[k+2, k+2] = -bath.rates[k]
        Σinitial[k+2, k+2] = real(bath.coefficients[k])
        Q[k+2, k+2] = 2bath.rates[k] * real(bath.coefficients[k])
    end
    # Van Loan block exponential evaluates ∫₀ᵗ exp(As)Q exp(A's) ds without
    # time stepping the reference or relying on the HEOM moment equations.
    propagator = exp(t * [A Q; zeros(dim, dim) -A'])
    F = propagator[1:dim, 1:dim]
    noise = propagator[1:dim, (dim+1):(2dim)] * F'
    μ = F * [μ0; zeros(modes)]
    Σ = F * Σinitial * F' + noise
    return μ[1:2], Symmetric(Σ[1:2, 1:2])
end

@testset "Drude HEOM converges to the full non-Markovian Gaussian solution" begin
    m, ω, ħ = 1.3, 0.85, 0.9
    bath = drude_lorentz_bath(;
        reorganization = 0.22,
        cutoff = 1.1,
        kT = 0.75,
        hbar = ħ,
        matsubara = 1,
    )
    grid = PhaseSpaceGrid((-8, 8), 64, (-8, 8), 64)
    μ0, Σ0 = [0.9, -0.4], [0.7 0.12; 0.12 0.6]
    W0 = on_grid((q, p) -> gaussian_wigner(q, p; mean = μ0, covariance = Σ0), grid)
    times = [0.4, 0.8, 1.2]
    reference = map(times) do t
        μ, Σ = gaussian_memory_reference(t, μ0, Σ0, bath; mass = m, omega = ω)
        on_grid((q, p) -> gaussian_wigner(q, p; mean = μ, covariance = Σ), grid)
    end
    errors = map((2, 4, 6)) do depth
        prob = heom_problem(
            W0,
            (0.0, last(times)),
            grid;
            mass = m,
            potential = harmonic_potential(; mass = m, omega = ω),
            bath,
            depth,
        )
        sol = solve(prob, Vern7(); abstol = 1e-10, reltol = 1e-10, saveat = times)
        for (t, U) in zip(sol.t, sol.u)
            W = physical_wigner(U)
            μ, Σ = gaussian_memory_reference(t, μ0, Σ0, bath; mass = m, omega = ω)
            @test phase_space_integral(W, grid) ≈ 1 atol = 2e-10
            @test phase_space_mean(W, grid) ≈ μ atol = 2e-8
            @test phase_space_covariance(W, grid) ≈ Σ atol = 2e-8
        end
        maximum(
            max_error(physical_wigner(U), exact) for (U, exact) in zip(sol.u, reference)
        )
    end
    # Moments through second order close at depth two, while the full distribution
    # still needs convergence in hierarchy depth. This catches non-Gaussian error
    # invisible to the existing moment-only benchmark.
    @test errors[2] < errors[1] / 10
    @test errors[3] < errors[2] / 10
    @test errors[3] < 2e-6
end
